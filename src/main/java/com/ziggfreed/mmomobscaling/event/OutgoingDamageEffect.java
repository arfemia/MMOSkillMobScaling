package com.ziggfreed.mmomobscaling.event;

import java.util.List;
import java.util.Locale;

import javax.annotation.Nonnull;
import javax.annotation.Nullable;

import com.ziggfreed.common.effect.grid.EffectBodies;
import com.ziggfreed.common.effect.grid.RuntimeEffectGrid;
import com.ziggfreed.mmomobscaling.scaling.MobScaleResult;

/**
 * A scaled mob's outgoing-damage multiplier ({@link MobScaleResult#outDmgMult}, every affix's
 * {@code FoldDeltas.OutDamage} already folded in) carried by a native {@code EntityEffect} with
 * {@code OutgoingDamage}: one shared runtime asset per step, written lazily by ziggfreed-common's
 * {@link RuntimeEffectGrid} the first time any mob rolls that step. {@link MobScalingEffectApplySystem}'s
 * reconcile puts it on the mob with the rest of the roll's effects.
 *
 * <p><b>Geometric steps.</b> A bucket is a whole number of {@link #STEP} multiplications ({@code n}, so the
 * mob deals {@code STEP^n} of a hit), the nearest to the folded multiplier: at most about 1% off it at any
 * size, and a bounded number of assets however far the difficulty curve reaches (each asset joins the
 * catalogue every client syncs, so a whole-percent grid over a curve that runs past 270x would mint
 * thousands).
 *
 * <p><b>Three root keys.</b> The engine's outgoing-damage step sums the modifiers of every active effect
 * whose key sits anywhere on the hit's {@code Inherits} chain, so the body keys only the roots
 * {@link #ROOT_CAUSES} and covers every type an entity deals (any type under one of them, vanilla's or a
 * pack's), with no hit paid twice. {@code Environment} and {@code Command} are deliberately not keyed; a
 * pack type with no parent at all goes unscaled on the outgoing side. That step runs in the
 * Filter group after armour: {@code max(0, amount * (1 + percent))}.
 *
 * <p><b>Under the mod's effect family.</b> Every id starts {@link MobScalingEffectApplySystem#EFFECT_PREFIX},
 * so the reconcile's own sweep drops a stale bucket (a re-roll at another step) and keeps the wanted
 * one, and {@code /mobscaling purge} clears it with the auras.
 */
final class OutgoingDamageEffect {

    /** Every bucket's id prefix ({@code Mmoscaling_OutDamage_}), under the mod's effect family. */
    static final String PREFIX = MobScalingEffectApplySystem.EFFECT_PREFIX + "OutDamage_";

    /** The one channel: a mob carries a single multiplier for every type it deals. */
    static final String CHANNEL = "All";

    /** The roots every entity-dealt damage type inherits from; disjoint, so no hit matches two. */
    static final List<String> ROOT_CAUSES = List.of("Physical", "Projectile", "Elemental");

    /** One step of the grid: each bucket is this many times the one below it. */
    static final double STEP = 1.02;

    /** The lowest step, about 1% of a hit: a multiplier at or under zero lands here. */
    static final int MIN_STEPS = -230;

    /** The asset pack the generated effects are loaded under. */
    private static final String PACK_KEY = "mmomobscaling";

    @Nonnull
    static final RuntimeEffectGrid GRID = new RuntimeEffectGrid(PREFIX, PACK_KEY, OutgoingDamageEffect::body);

    private OutgoingDamageEffect() {
    }

    /**
     * The step count for a folded multiplier: {@code round(ln(outDmgMult) / ln(STEP))}, at least
     * {@link #MIN_STEPS}; a non-finite reading is 0. The fold's own rail already caps the top.
     */
    static int stepsFor(double outDmgMult) {
        if (!Double.isFinite(outDmgMult)) {
            return 0;
        }
        if (outDmgMult <= 0.0) {
            return MIN_STEPS;
        }
        return RuntimeEffectGrid.bucketFor(Math.log(outDmgMult) / Math.log(STEP), MIN_STEPS, Integer.MAX_VALUE);
    }

    /** The outgoing fraction a step count carries: {@code STEP^steps - 1} (25 steps is about +64%). */
    static double fractionFor(int steps) {
        return Math.pow(STEP, steps) - 1.0;
    }

    /** The bucket a roll carries, or {@code null} when its multiplier rounds to no change (no effect at all). */
    @Nullable
    static RuntimeEffectGrid.Bucket bucketFor(@Nonnull MobScaleResult result) {
        int steps = stepsFor(result.outDmgMult());
        return steps == 0 ? null : new RuntimeEffectGrid.Bucket(CHANNEL, steps);
    }

    /** The generated effect id for {@code bucket}, e.g. {@code Mmoscaling_OutDamage_All_25}. */
    @Nonnull
    static String effectId(@Nonnull RuntimeEffectGrid.Bucket bucket) {
        return GRID.effectId(bucket);
    }

    /** The bucket's infinite, invisible body: one {@code Percent} modifier of {@code STEP^n - 1} on each root. */
    @Nonnull
    private static String body(@Nonnull RuntimeEffectGrid.Bucket bucket) {
        double fraction = fractionFor(bucket.value());
        String comment = String.format(Locale.ROOT,
                "Generated by MMO Mob Scaling: a scaled mob's rolled outgoing damage, x%.3f on every hit it deals.",
                1.0 + fraction);
        return EffectBodies.damageModifiers(EffectBodies.OUTGOING_DAMAGE, ROOT_CAUSES, EffectBodies.PERCENT,
                fraction, comment, true);
    }
}
